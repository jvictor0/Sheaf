#!/usr/bin/env python3
"""Bind Lean's real filter model to the bridge's actual binary32 coefficients."""
import argparse
from fractions import Fraction
import json
import os
from pathlib import Path
import shlex
import struct
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--write', action='store_true', help='write a newly reviewed coefficient snapshot and Lean definitions')
args = parser.parse_args()
with tempfile.TemporaryDirectory(prefix='sheaf-alias-coefficients-') as directory:
    binary = Path(directory) / 'coefficients'
    subprocess.run(shlex.split(os.environ.get('CXX', 'c++')) + [
        '-std=c++20', '-O2', '-DNDEBUG', '-I' + str(root / 'include'),
        str(root / 'formal/support/source_filter_coefficients.cpp'), '-o', str(binary)], check=True)
    actual = json.loads(subprocess.check_output([str(binary)], text=True))
if len(actual) != 4 or any(len(section) != 5 for section in actual):
    raise SystemExit('Expected four five-coefficient source-filter sections')

snapshot = root / 'formal/source-filter-coefficients.json'
model = root / 'formal/Sheaf/SourceFilterCoefficients.lean'
lines = ['import Mathlib.Data.Real.Basic', '',
         '-- Exact binary32 values exported from the configured C++ bridge.',
         '-- Generated by scripts/check_source_filter_coefficients.py --write after review.',
         'namespace Sheaf.SourceFilterCoefficients', '',
         'structure Biquad where', '  b0 : ℝ', '  b1 : ℝ', '  b2 : ℝ', '  a1 : ℝ', '  a2 : ℝ', '']
for index, section in enumerate(actual):
    lines.append(f'noncomputable def section{index} : Biquad := {{')
    for field, bits in zip(('b0', 'b1', 'b2', 'a1', 'a2'), section):
        value = Fraction(struct.unpack('!f', struct.pack('!I', bits))[0])
        lines.append(f'  {field} := ({value.numerator} : ℝ) / {value.denominator}')
    lines.extend(['}', ''])
lines.extend(['end Sheaf.SourceFilterCoefficients', ''])
expected_model = '\n'.join(lines)
if args.write:
    snapshot.write_text(json.dumps(actual, indent=2) + '\n')
    model.write_text(expected_model)
else:
    if json.loads(snapshot.read_text()) != actual:
        raise SystemExit('Source-filter coefficients changed; review the alias proof before refreshing the snapshot')
    if model.read_text() != expected_model:
        raise SystemExit('Lean source-filter coefficients differ from the exact C++ export')
print('Verified 20 exact binary32 source-filter coefficients')
