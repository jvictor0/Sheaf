#!/usr/bin/env python3
"""Generate kernel-checked Bernstein witnesses from exported binary32 bits.

Python proposes exact rational identities. Lean checks every identity, sign and
closed interval union. No numerical design library participates in this path.
"""
from fractions import Fraction as F
from math import comb
from pathlib import Path
import argparse
import json
import struct

root = Path(__file__).resolve().parents[1]

def mul(a, b):
    result = [F(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            result[i+j] += x*y
    return result

def magnitude(a, b, c):
    return [a*a+b*b+c*c-2*a*c, 2*b*(a+c), 4*a*c]

def bernstein(p, l, r):
    n = len(p)-1
    q = [sum(p[j]*comb(j,k)*l**(j-k)*(r-l)**k for j in range(k,n+1)) for k in range(n+1)]
    return [sum(q[k]*F(comb(i,k),comb(n,k)) for k in range(i+1)) for i in range(n+1)]

def rat(x):
    return f'({x.numerator}/{x.denominator}:ℝ)'

def polynomial(p, x):
    return ' + '.join(f'{rat(v)}*({x})^{i}' for i,v in enumerate(p) if v)

def generate():
    rows = json.loads((root/'formal/source-filter-coefficients.json').read_text())
    if len(rows) != 6 or any(len(row) != 5 for row in rows):
        raise ValueError('Expected six five-coefficient exported sections')
    n, d = [F(1)], [F(1)]
    for row in rows:
        b0,b1,b2,a1,a2 = [F(struct.unpack('!f',struct.pack('!I',bits))[0]) for bits in row]
        n = mul(n,magnitude(b0,b1,b2))
        d = mul(d,magnitude(F(1),a1,a2))
    lines = ['import Sheaf.ResponseCore', '',
             '-- Generated by scripts/generate_source_filter_certificate.py; do not edit.',
             '-- Every exported-product identity and Bernstein witness is checked by Lean.',
             'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0',
             'namespace Sheaf.SourceFilterCertificate', 'open Sheaf.Aliasing Sheaf.SourceFilterCoefficients', '']
    for name,p,actual in [('N',n,'actualNumerator'),('D',d,'actualDenominator')]:
        lines += [f'noncomputable def {name} (c : ℝ) : ℝ := {polynomial(p,"c")}', '',
                  f'theorem {name}_matches_actual (c : ℝ) : {name} c = {actual} c := by',
                  f'  simp only [{name}, {actual}, actualSections, List.map_cons, List.map_nil, List.prod_cons, List.prod_nil]',
                  '  dsimp [numerator, denominator, section0, section1, section2, section3, section4, section5]',
                  '  ring', '']
    targets = [('stop', [F(981,1000*10**9)*v-u for u,v in zip(n,d)], F(-1),F(707107,1000000), '(981/1000000000000:ℝ)*D c-N c'),
               ('lower',[u-F(981,1000)*v for u,v in zip(n,d)], F(793353,1000000),F(1),'N c-(981/1000:ℝ)*D c'),
               ('upper',[F(10001,10000)*v-u for u,v in zip(n,d)],F(793353,1000000),F(1),'(10001/10000:ℝ)*D c-N c')]
    for name,p,lo,hi,expr in targets:
        lines += [f'noncomputable def {name}Polynomial (c : ℝ) : ℝ := {expr}', '']
        leaves=[]
        def walk(l,r,depth=0):
            b=bernstein(p,l,r)
            if min(b)>=0:
                i=len(leaves); leaves.append((l,r,b)); return i
            if depth==24:
                raise ValueError(f'No positive Bernstein witness for {name} [{l},{r}]')
            m=(l+r)/2
            return (m,walk(l,m,depth+1),walk(m,r,depth+1))
        tree=walk(lo,hi)
        degree=len(p)-1
        for i,(l,r,b) in enumerate(leaves):
            basis=' + '.join(f'{rat(v*comb(degree,k))}*t^{k}*(1-t)^{degree-k}' for k,v in enumerate(b) if v)
            lines += [f'theorem {name}_leaf_{i} (t : ℝ) (ht : 0 ≤ t) (hu : t ≤ 1) :',
                      f'    0 ≤ {name}Polynomial ({rat(l)}+({rat(r-l)})*t) := by',
                      '  have h1 : 0 ≤ 1-t := by linarith',
                      f'  have hid : {name}Polynomial ({rat(l)}+({rat(r-l)})*t) = {basis} := by',
                      f'    unfold {name}Polynomial N D', '    ring', '  rw [hid]', '  positivity', '']
        lines += [f'theorem {name}_whole (c : ℝ) (lo : {rat(lo)} ≤ c) (hi : c ≤ {rat(hi)}) :',
                  f'    0 ≤ {name}Polynomial c := by']
        def assemble(node,indent):
            pad=' '*indent
            if isinstance(node,int):
                l,r,_=leaves[node]
                lines.append(pad+f'apply interval_transfer {name}Polynomial {rat(l)} {rat(r)} c (by norm_num) (by linarith) (by linarith)')
                lines.append(pad+f'simpa only [show {rat(r)}-{rat(l)} = {rat(r-l)} by norm_num] using {name}_leaf_{node}')
            else:
                m,left,right=node
                lines.append(pad+f'by_cases h{indent} : c ≤ {rat(m)}')
                lines.append(pad+'·')
                assemble(left,indent+2)
                lines.append(pad+'·')
                assemble(right,indent+2)
        assemble(tree,2)
        lines.append('')
    lines += ['end Sheaf.SourceFilterCertificate','']
    return '\n'.join(lines)

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    result=generate()
    path=root/'formal/Sheaf/SourceFilterCertificate.lean'
    if args.write:
        path.write_text(result)
        print('Generated exact six-section closed-band Bernstein certificate')
    elif path.read_text()!=result:
        raise SystemExit('Source-filter certificate differs from exported-bit generation')
    else:
        print('Verified exact exported-bit Bernstein certificate generation')
